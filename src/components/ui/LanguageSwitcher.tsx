interface LocaleContextType {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const LocaleContext = createContext<LocaleContextType>({
  locale: "es",
  setLocale: () => {},
  t: (k) => k,
});

function loadLocale(): Locale {
  if (typeof window === "undefined") return "es";
  try {
    const v = localStorage.getItem("trinax-locale");
    if (v === "en") return "en";
  } catch {}
  return "es";
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("es");

  useEffect(() => {
    setLocaleState(loadLocale());
  }, []);

  const setLocale = useCallback((l: Locale) => {
    localStorage.setItem("trinax-locale", l);
    setLocaleState(l);
  }, []);

  const t = useCallback(
    (key: string) => translations[locale]?.[key] ?? key,
    [locale],
  );

  return (
    <LocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </LocaleContext.Provider>
  );
}

export function useT() {
  return useContext(LocaleContext);
}

export function LanguageSwitcher() {
  const { locale, setLocale } = useT();

  return (
    <div className="flex items-center gap-0.5 rounded-lg bg-white/[0.03] p-0.5">
      <button
        onClick={() => setLocale("es")}
        className={`rounded-md px-2 py-1 text-[10px] font-semibold uppercase tracking-wider transition-all ${
          locale === "es" ? "bg-white/10 text-white shadow-sm" : "text-white/25 hover:text-white/50"
        }`}
      >
        ES
      </button>
      <button
        onClick={() => setLocale("en")}
        className={`rounded-md px-2 py-1 text-[10px] font-semibold uppercase tracking-wider transition-all ${
          locale === "en" ? "bg-white/10 text-white shadow-sm" : "text-white/25 hover:text-white/50"
        }`}
      >
        EN
      </button>
    </div>
  );
}
